-- BC Gestão — agenda pública e disponibilidade da equipe (schema)
-- Migration aditiva. Não abre tabelas operacionais diretamente ao navegador.

-- Reservas do site ainda não possuem identidade clínica confirmada.
alter table public.agendamentos
  alter column cliente_id drop not null,
  alter column created_by drop not null,
  add column if not exists origem text not null default 'interno',
  add column if not exists public_booking_name text,
  add column if not exists public_booking_phone text,
  add column if not exists public_booking_phone_normalized text;

alter table public.agendamentos
  drop constraint if exists agendamentos_origem_check,
  add constraint agendamentos_origem_check
    check (origem in ('interno', 'site')),
  drop constraint if exists agendamentos_identity_by_origin_check,
  add constraint agendamentos_identity_by_origin_check
    check (
      (origem = 'interno' and cliente_id is not null and created_by is not null)
      or
      (
        origem = 'site'
        and nullif(trim(public_booking_name), '') is not null
        and nullif(trim(public_booking_phone), '') is not null
        and public_booking_phone_normalized ~ '^[0-9]{10,13}$'
      )
    );

comment on column public.agendamentos.origem is
  'Origem operacional do compromisso: interno ou site.';
comment on column public.agendamentos.public_booking_name is
  'Snapshot do nome informado em reserva pública; não é identidade clínica confirmada.';
comment on column public.agendamentos.public_booking_phone is
  'Snapshot do WhatsApp informado em reserva pública.';
comment on column public.agendamentos.public_booking_phone_normalized is
  'Telefone público normalizado para operação; não autoriza vínculo automático a prontuário.';

create table if not exists public.professional_availability_days (
  id uuid primary key default gen_random_uuid(),
  professional_user_id uuid not null references auth.users(id) on delete restrict,
  local_date date not null,
  enabled boolean not null default true,
  start_time time,
  end_time time,
  created_by uuid not null references auth.users(id) on delete restrict,
  updated_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (professional_user_id, local_date),
  constraint professional_availability_days_window_check
    check (
      (enabled = false)
      or
      (start_time is not null and end_time is not null and end_time > start_time)
    )
);

create table if not exists public.professional_schedule_blocks (
  id uuid primary key default gen_random_uuid(),
  professional_user_id uuid not null references auth.users(id) on delete restrict,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  block_type text not null,
  internal_note text,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint professional_schedule_blocks_window_check check (ends_at > starts_at),
  constraint professional_schedule_blocks_type_check
    check (block_type in ('almoco', 'compromisso', 'reuniao', 'preparacao_manutencao', 'outro'))
);

create table if not exists public.professional_agenda_inactivations (
  id uuid primary key default gen_random_uuid(),
  professional_user_id uuid not null references auth.users(id) on delete restrict,
  starts_on date not null,
  planned_ends_on date,
  reason text not null,
  internal_note text,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now(),
  reactivated_at timestamptz,
  reactivated_by uuid references auth.users(id) on delete restrict,
  constraint professional_agenda_inactivations_period_check
    check (planned_ends_on is null or planned_ends_on >= starts_on),
  constraint professional_agenda_inactivations_reason_check
    check (reason in (
      'ferias',
      'motivos_pessoais',
      'motivo_medico',
      'licenca_afastamento',
      'curso_capacitacao',
      'viagem',
      'folga',
      'outro'
    )),
  constraint professional_agenda_inactivations_reactivation_check
    check (
      (reactivated_at is null and reactivated_by is null)
      or
      (reactivated_at is not null and reactivated_by is not null)
    )
);

-- Estrutura privada para antiabuso. Somente hash da origem; nunca IP bruto.
create table if not exists private.public_booking_rate_limits (
  id bigint generated by default as identity primary key,
  origin_hash text not null check (char_length(origin_hash) between 32 and 128),
  attempted_at timestamptz not null default now()
);

create index if not exists professional_schedule_blocks_range_idx
  on public.professional_schedule_blocks (professional_user_id, starts_at, ends_at);

create index if not exists professional_agenda_inactivations_period_idx
  on public.professional_agenda_inactivations (professional_user_id, starts_on, planned_ends_on);

create index if not exists public_booking_rate_limits_origin_time_idx
  on private.public_booking_rate_limits (origin_hash, attempted_at);

alter table public.professional_availability_days enable row level security;
alter table public.professional_schedule_blocks enable row level security;
alter table public.professional_agenda_inactivations enable row level security;

-- RPC-only: as interfaces autenticadas e a Edge Function ganharão apenas EXECUTE
-- nas funções específicas da próxima migration.
revoke all on table public.professional_availability_days from anon, authenticated;
revoke all on table public.professional_schedule_blocks from anon, authenticated;
revoke all on table public.professional_agenda_inactivations from anon, authenticated;
revoke all on table private.public_booking_rate_limits from public, anon, authenticated;

-- Reafirma que o papel público não ganha novos privilégios sobre agendamentos.
revoke all on table public.agendamentos from anon;
